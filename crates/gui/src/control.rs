use serde::{Deserialize, Serialize};

/// The profile-info control message: local display name/status, so
/// "Connected" can show who you're actually talking to instead of just
/// their address. `net`/`protocol` don't know this type exists -- it's
/// just bytes to them, encoded/decoded entirely on this side of the wire.
#[derive(Serialize, Deserialize, Clone, Debug)]
pub struct Hello {
    pub display_name: String,
    pub status_message: String,
    /// Presence (spec §7), as an integer -- see `crate::presence`.
    ///
    /// Defaulted so a peer on an older build is understood. Absent means
    /// the same thing as invisible: nothing was said, so nothing is shown.
    #[serde(default)]
    pub presence: Option<i32>,
    /// The caller started this call as a knock (spec §9).
    ///
    /// Carried here rather than only as a separate `SilentCall` message so
    /// the intent arrives with the *first* thing sent, instead of whenever
    /// a button is pressed. Like `SilentCall`, it can only lower the
    /// receiver's outcome -- there is no field here that raises one.
    ///
    /// Defaulted, so a peer on an older build is understood as not
    /// knocking, which is what a missing field should mean.
    #[serde(default)]
    pub wants_silent: bool,
    /// The relay this person listens at, `host:port`, or empty (spec §3).
    /// Sent so a contact can reach you through it next time without
    /// exchanging another link. Defaulted for peers on older builds.
    #[serde(default)]
    pub relay: String,
    /// This person's signed route list (spec §8), hex: where to leave
    /// mail for them while they're offline. Defaulted for older builds.
    #[serde(default)]
    pub routes: String,
}

/// Note on trust: none of these messages are authenticated beyond the
/// session's own encryption. The X25519 handshake is ephemeral -- there's
/// no persistent identity key -- so `FriendRequest` proves only "whoever
/// is at this address, right now", not "this specific person". Contact
/// pinning/verification is real work that isn't done; see the README.
///
/// Every kind of message this app sends over `PeerConnection::send_control`
/// (spec §1 profile info, spec §5 file transfer offers/acks). Internally
/// tagged by `kind` so a receiver can tell them apart -- `Hello` used to be
/// the only shape sent, decoded unconditionally; adding file transfer
/// meant something had to disambiguate. Unknown/malformed payloads still
/// just decode to `None` and get dropped (see `state::start_pipeline`),
/// same tolerance as before -- a peer running an older version sending
/// bare `Hello` JSON without this wrapper would no longer decode, but
/// there's no shipped version to be compatible with yet.
#[derive(Serialize, Deserialize, Clone, Debug)]
#[serde(tag = "kind")]
pub enum ControlMessage {
    Hello(Hello),
    /// Announces intent to send a file (spec §5). `chunk_count` and
    /// `sha256` let the receiver size its `FileReassembler` and verify
    /// integrity once every chunk has arrived.
    FileOffer {
        transfer_id: u64,
        file_name: String,
        file_size: u64,
        chunk_count: u32,
        sha256: String,
        /// A small PNG preview, generated by the *sender* (spec §5).
        ///
        /// Base64 so it survives JSON. Defaulted, so an offer without one
        /// is understood rather than dropped -- most files have no
        /// meaningful preview and a transfer must not depend on it.
        #[serde(default)]
        thumbnail_png_b64: String,
    },
    /// A file that stays fetchable after the call (spec §5 seeding and
    /// pinning): its own key, its id, and who holds sealed copies. Only
    /// ever sent inside the call's encrypted channel -- the key is the
    /// whole of the access.
    FileLink {
        name: String,
        size: u64,
        file_id: String,
        key: String,
        /// The sender's seeding port on the address the call came from,
        /// or 0 when they aren't seeding.
        #[serde(default)]
        seed_port: u16,
        /// Pin nodes that took a copy, as `ip:port`.
        #[serde(default)]
        holders: Vec<String>,
    },
    /// Receiver agreed; the sender can start blasting `File` frames.
    FileAccept { transfer_id: u64 },
    /// Receiver declined; the sender should drop the transfer.
    FileReject { transfer_id: u64 },
    /// Sent by the receiver after the initial blast of chunks goes quiet,
    /// listing whatever's still missing (UDP has no delivery guarantee) --
    /// the sender resends just those.
    FileMissing { transfer_id: u64, indices: Vec<u32> },
    /// Receiver confirms every chunk arrived and passed hash verification.
    FileComplete { transfer_id: u64 },
    /// Either side can cancel an in-progress transfer.
    FileCancel { transfer_id: u64 },
    /// "I never got these audio frames, send them again" (spec §2's
    /// retransmit layer).
    ///
    /// Carries *application* frame sequence numbers, not crypto counters:
    /// a resend reuses the sequence so it lands in the right slot, while
    /// getting a fresh crypto counter, because reusing an AEAD nonce would
    /// be catastrophic. See `antiphon_net::fec`.
    AudioMissing { sequences: Vec<u32> },
    /// "I am here if you want to talk" -- a silent call (spec §9).
    ///
    /// A *request* for less attention, never more: the receiver's own
    /// rules still decide what happens, and this can only lower the
    /// outcome. See `crate::notify::decide`.
    SilentCall,
    /// "Actually, this is worth your attention" -- escalating a knock to a
    /// ring without hanging up and calling back (spec §9).
    ///
    /// It withdraws the caller's *own* silencing and nothing more. The
    /// receiver's rules are re-read on their machine and still decide; a
    /// contact set to never ring still never rings. There is deliberately
    /// no message here that can raise an outcome, only one that can stop
    /// lowering it.
    EscalateCall,
    /// One in-call text message (spec §4) -- same encrypted control
    /// channel as everything else, so chat gets the session's encryption
    /// and replay protection for free. No delivery tiers/offline queueing
    /// (spec §4's "tiered delivery"): chat only exists while a call is up.
    Chat {
        /// Sender-chosen id, unique within this conversation, so a later
        /// edit or delete can say which message it means (spec §13).
        #[serde(default)]
        id: u64,
        text: String,
    },
    /// The sender revised one of their own messages (spec §13 "edit").
    ///
    /// A peer can only ever edit messages they sent -- the receiver
    /// enforces that, because otherwise an "edit" would be a way to
    /// rewrite the other person's words after the fact.
    ChatEdit { id: u64, text: String },
    /// The sender withdrew one of their own messages (spec §13 "delete").
    ///
    /// Tombstoned rather than removed on the receiving side: a message that
    /// vanishes without trace is indistinguishable from one that never
    /// arrived, which is worse for the person left wondering.
    ChatDelete { id: u64 },
    /// Added or removed a reaction on a message (spec §13).
    ///
    /// A toggle rather than separate add/remove messages: the sender's
    /// state after the tap is what matters, and two messages would let the
    /// two sides disagree about whether a reaction is on.
    ChatReact { message_id: u64, emoji: String },
    /// "Here is someone else's key" (spec §4 contact introduction).
    ///
    /// Carries evidence about *provenance*, not trust: the receiver records
    /// who passed it along and still treats the contact as unverified.
    /// Anything else would let one compromised contact launder keys into
    /// everyone else's address book.
    Introduce { identity_key: String, petname: String, note: String },
    /// "Add me to your contacts" (spec §3 "Known contacts"). Carries the
    /// sender's display name only -- see `ControlMessage`'s note above and
    /// the README on what this does *not* authenticate.
    FriendRequest { display_name: String },
    /// Accepted: the requester adds the accepter back, so both ends end up
    /// with the contact rather than only one side.
    FriendAccept { display_name: String },
    FriendReject,
    /// Group calls (spec §3 "up to ~5 people, direct mesh"): the person
    /// who added someone asks two members to connect to each other through
    /// a relay. `dial` says which side dials and which registers and
    /// listens; `peer_key` is who must answer, checked against the
    /// handshake so a stranger who learned the token can't slip in.
    GroupConnect { pair: u64, peer_key: String, relay: String, token: String, dial: bool },
    /// The same without a relay: find your public address on a fresh
    /// socket and report it, so the two members can punch through to each
    /// other directly.
    GroupPunch { pair: u64, peer_key: String },
    GroupPunchAddr { pair: u64, addr: String },
    GroupPunchPeer { pair: u64, peer_key: String, addr: String },
    /// Leaving the group call. The 1:1 path has no hang-up message; a
    /// group needs one, or everyone else keeps mixing a silent leg.
    GroupLeave,
    /// The call has moved past the mesh to an SFU (spec §3 "Beyond that --
    /// SFU relay"): join the room at `sfu` named by `secret` and `day`.
    /// Sent only over the call's own end-to-end sessions, so the SFU never
    /// learns the secret. See `crate::sfu_call`.
    GroupSfu { sfu: String, secret: String, day: u64 },
}

impl ControlMessage {
    pub fn encode(&self) -> Vec<u8> {
        serde_json::to_vec(self).expect("ControlMessage only contains strings/numbers, never fails to serialize")
    }

    pub fn decode(bytes: &[u8]) -> Option<Self> {
        serde_json::from_slice(bytes).ok()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hello_round_trips_through_the_wrapper() {
        let msg = ControlMessage::Hello(Hello {
            display_name: "Alice".to_string(),
            status_message: "Away".to_string(),
            presence: Some(1),
            wants_silent: true,
            relay: "relay.example:3479".to_string(),
            routes: String::new(),
        });
        let decoded = ControlMessage::decode(&msg.encode()).unwrap();
        match decoded {
            ControlMessage::Hello(h) => {
                assert_eq!(h.display_name, "Alice");
                assert_eq!(h.status_message, "Away");
                assert!(h.wants_silent);
            }
            other => panic!("expected Hello, got {other:?}"),
        }
    }

    #[test]
    fn a_greeting_from_a_peer_who_predates_knocking_is_not_a_knock() {
        // A missing field must read as "did not knock". Defaulting the
        // other way would silence calls from anyone on an older build.
        let json = br#"{"kind":"Hello","display_name":"Bob","status_message":""}"#;
        match ControlMessage::decode(json).unwrap() {
            ControlMessage::Hello(h) => assert!(!h.wants_silent),
            other => panic!("expected Hello, got {other:?}"),
        }
    }

    #[test]
    fn an_offer_without_a_thumbnail_still_decodes() {
        // Most files have no preview, and a transfer must never depend on
        // one being present.
        let raw = br#"{"kind":"FileOffer","transfer_id":1,"file_name":"a.txt","file_size":2,"chunk_count":1,"sha256":"ab"}"#;
        match ControlMessage::decode(raw).unwrap() {
            ControlMessage::FileOffer { thumbnail_png_b64, .. } => {
                assert!(thumbnail_png_b64.is_empty());
            }
            other => panic!("expected FileOffer, got {other:?}"),
        }
    }

    #[test]
    fn a_hello_from_before_presence_existed_still_decodes() {
        // A peer on an older build says nothing about presence, which
        // means nothing is shown -- the same as invisible.
        let raw = br#"{"kind":"Hello","display_name":"Bob","status_message":""}"#;
        match ControlMessage::decode(raw).unwrap() {
            ControlMessage::Hello(h) => assert!(h.presence.is_none()),
            other => panic!("expected Hello, got {other:?}"),
        }
    }

    #[test]
    fn file_offer_round_trips() {
        let msg = ControlMessage::FileOffer {
            transfer_id: 7,
            file_name: "preset.json".to_string(),
            file_size: 12345,
            chunk_count: 4,
            sha256: "abcd".to_string(),
            thumbnail_png_b64: String::new(),
        };
        let decoded = ControlMessage::decode(&msg.encode()).unwrap();
        match decoded {
            ControlMessage::FileOffer { transfer_id, file_name, file_size, chunk_count, sha256, .. } => {
                assert_eq!(transfer_id, 7);
                assert_eq!(file_name, "preset.json");
                assert_eq!(file_size, 12345);
                assert_eq!(chunk_count, 4);
                assert_eq!(sha256, "abcd");
            }
            other => panic!("expected FileOffer, got {other:?}"),
        }
    }

    #[test]
    fn file_missing_round_trips_the_index_list() {
        let msg = ControlMessage::FileMissing { transfer_id: 1, indices: vec![2, 5, 9] };
        let decoded = ControlMessage::decode(&msg.encode()).unwrap();
        match decoded {
            ControlMessage::FileMissing { indices, .. } => assert_eq!(indices, vec![2, 5, 9]),
            other => panic!("expected FileMissing, got {other:?}"),
        }
    }

    #[test]
    fn chat_round_trips() {
        let msg = ControlMessage::Chat { id: 42, text: "hey, can you hear me?".to_string() };
        match ControlMessage::decode(&msg.encode()).unwrap() {
            ControlMessage::Chat { id, text } => {
                assert_eq!(id, 42);
                assert_eq!(text, "hey, can you hear me?");
            }
            other => panic!("expected Chat, got {other:?}"),
        }
    }

    #[test]
    fn an_edit_names_the_message_it_revises() {
        let msg = ControlMessage::ChatEdit { id: 7, text: "fixed typo".to_string() };
        match ControlMessage::decode(&msg.encode()).unwrap() {
            ControlMessage::ChatEdit { id, text } => {
                assert_eq!(id, 7);
                assert_eq!(text, "fixed typo");
            }
            other => panic!("expected ChatEdit, got {other:?}"),
        }
    }

    #[test]
    fn an_escalation_round_trips() {
        assert!(matches!(
            ControlMessage::decode(&ControlMessage::EscalateCall.encode()),
            Some(ControlMessage::EscalateCall)
        ));
    }

    #[test]
    fn escalating_is_a_different_message_from_knocking() {
        // Sharing an encoding would make a knock and its withdrawal
        // indistinguishable on the wire, and the receiver would have to
        // guess which one it just got.
        assert_ne!(
            ControlMessage::EscalateCall.encode(),
            ControlMessage::SilentCall.encode()
        );
    }

    #[test]
    fn a_silent_call_marker_round_trips() {
        let msg = ControlMessage::SilentCall;
        assert!(matches!(
            ControlMessage::decode(&msg.encode()).unwrap(),
            ControlMessage::SilentCall
        ));
    }

    #[test]
    fn an_introduction_round_trips() {
        let msg = ControlMessage::Introduce {
            identity_key: "ab".repeat(32),
            petname: "Bob".to_string(),
            note: "from the climbing group".to_string(),
        };
        match ControlMessage::decode(&msg.encode()).unwrap() {
            ControlMessage::Introduce { identity_key, petname, note } => {
                assert_eq!(identity_key, "ab".repeat(32));
                assert_eq!(petname, "Bob");
                assert_eq!(note, "from the climbing group");
            }
            other => panic!("expected Introduce, got {other:?}"),
        }
    }

    #[test]
    fn a_reaction_round_trips() {
        let msg = ControlMessage::ChatReact { message_id: 3, emoji: "👍".to_string() };
        match ControlMessage::decode(&msg.encode()).unwrap() {
            ControlMessage::ChatReact { message_id, emoji } => {
                assert_eq!(message_id, 3);
                assert_eq!(emoji, "👍");
            }
            other => panic!("expected ChatReact, got {other:?}"),
        }
    }

    #[test]
    fn a_delete_round_trips() {
        let msg = ControlMessage::ChatDelete { id: 9 };
        match ControlMessage::decode(&msg.encode()).unwrap() {
            ControlMessage::ChatDelete { id } => assert_eq!(id, 9),
            other => panic!("expected ChatDelete, got {other:?}"),
        }
    }

    #[test]
    fn a_chat_from_before_ids_existed_still_decodes() {
        // `id` is defaulted, so a peer on an older build sending a bare
        // Chat is understood rather than dropped.
        let raw = br#"{"kind":"Chat","text":"hello"}"#;
        match ControlMessage::decode(raw).unwrap() {
            ControlMessage::Chat { id, text } => {
                assert_eq!(id, 0);
                assert_eq!(text, "hello");
            }
            other => panic!("expected Chat, got {other:?}"),
        }
    }

    #[test]
    fn garbage_bytes_decode_to_none_not_a_panic() {
        assert!(ControlMessage::decode(b"not json at all").is_none());
    }
}
